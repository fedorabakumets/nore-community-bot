def staff_guide_text() -> str:
    lines = [
        "🛡 <b>Справка админки НОРЫ</b>",
        "Только для штаба. Участники этот текст не видят.",
        "",
    ]
    for heading, body in SECTIONS:
        lines.append(f"<b>{heading}</b>")
        lines.append(body)
        lines.append("")
    lines.append("Примеры всегда ответом на живое сообщение, кроме разбана по ID и чистки чата.")
    return "\n".join(lines).strip()


def _plain(html_text: str) -> str:
    return (
        html_text.replace("<b>", "")
        .replace("</b>", "")
        .replace("<code>", "")
        .replace("</code>", "")
        .strip()
    )


def staff_guide_nodes() -> list[dict[str, Any]]:
    nodes: list[dict[str, Any]] = [
        {"tag": "h3", "children": ["Справка админки НОРЫ"]},
        {
            "tag": "p",
            "children": ["Полный разбор штабных команд. Участники эту страницу не видят."],
        },
    ]
    for heading, body in SECTIONS:
        nodes.append({"tag": "h4", "children": [heading]})
        for chunk in body.split("\n\n"):
            text = _plain(chunk)
            if not text:
                continue
            if text.startswith("/") or "Пример" in text or text.startswith("•"):
                nodes.append({"tag": "blockquote", "children": [text]})
            else:
                nodes.append({"tag": "p", "children": [text]})
    return nodes
