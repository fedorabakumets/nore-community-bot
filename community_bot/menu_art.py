def render_cover(key: str, *, destination: Path | None = None, subtitle: str = "") -> Path:
    spec = COVERS[key]
    atlas = ART / f"atlas-{spec.atlas:02}.webp"
    path = destination or CACHE / f"{key}.png"
    if path.is_file() and path.stat().st_mtime >= max(
        atlas.stat().st_mtime, FONT_PATH.stat().st_mtime, Path(__file__).stat().st_mtime,
    ):
        return path
    with Image.open(atlas) as source:
        width, height = source.size
        column, row = spec.cell % 2, spec.cell // 2
        # Atlas extraction is mechanical; all character artwork is generated by image_gen.
        tile = source.crop((column * width // 2, row * height // 2,
                            (column + 1) * width // 2, (row + 1) * height // 2))
        image = tile.convert("RGB").resize(SIZE, Image.Resampling.LANCZOS)
    draw = ImageDraw.Draw(image)
    draw.fontmode = "1"
    heading = ImageFont.truetype(str(FONT_PATH), TITLE_SIZE)
    brand = ImageFont.truetype(str(FONT_PATH), BRAND_SIZE)
    draw.text((48, 40), "NORA", font=brand, fill=RED, anchor="lt")
    draw.rectangle((48, 212, 116, 215), fill=RED)
    for index, line in enumerate(spec.title.splitlines()):
        if heading.getlength(line) > 340:
            raise ValueError(f"Cover title does not fit the common grid: {key}")
        draw.text((TITLE_ORIGIN[0], TITLE_ORIGIN[1] + LINE_HEIGHT * index),
                  line, font=heading, fill=WHITE, anchor="lt")
    if subtitle:
        draw.text((48, 420), subtitle, font=brand, fill=RED, anchor="lt")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(".tmp.png")
    image.save(temporary, "PNG", optimize=True)
    temporary.replace(path)
    return path


def menu_cover(key: str) -> Path | None:
    return render_cover(key) if key in COVERS else None


