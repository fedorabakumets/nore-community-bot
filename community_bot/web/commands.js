  async function copyCommand(command) {
    if (navigator.clipboard?.writeText) {
      try {
        await navigator.clipboard.writeText(command);
        return true;
      } catch {
        // Some Telegram WebViews require selecting the text before copying.
      }
    }
    const previous = document.activeElement;
    const field = document.createElement('textarea');
    field.value = command;
    field.readOnly = true;
    field.style.cssText = 'position:fixed;top:0;left:0;opacity:0;font-size:16px';
    document.body.append(field);
    try {
      field.focus({preventScroll: true});
      field.select();
      field.setSelectionRange(0, command.length);
      return document.execCommand('copy');
    } catch {
      return false;
    } finally {
      field.remove();
      previous?.focus({preventScroll: true});
    }
  }

  document.addEventListener('click', async event => {
    const button = event.target.closest('button[data-copy-command]');
    if (!button) return;
    const command = button.dataset.copyCommand;
    if (await copyCommand(command)) {
      toast(NoraI18n.t("Команда скопирована"));
      return;
    }
    sheet(`<h2>${NoraI18n.html("Скопируй команду")}</h2><textarea rows="2" aria-label="${NoraI18n.html("Команда")}" readonly>${esc(command)}</textarea>`);
    const field = document.querySelector('#sheet textarea');
    field.focus();
    field.select();
  });

