def commands_keyboard(url: str) -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(
        inline_keyboard=[[InlineKeyboardButton(text="Читать команды", url=url)]]
    )


def commands_guide_nodes() -> list[dict[str, Any]]:
    nodes: list[dict[str, Any]] = [
        {"tag": "h3", "children": ["Команды НОРЫ"]},
        {
            "tag": "p",
            "children": [
                "Как писать боту в чате и в личке. У каждой команды есть пример, его можно скопировать почти дословно."
            ],
        },
    ]
    for heading, paragraphs, examples in _SECTIONS:
        nodes.append({"tag": "h4", "children": [heading]})
        for paragraph in paragraphs:
            nodes.append({"tag": "p", "children": [paragraph]})
        for example in examples:
            nodes.append({"tag": "blockquote", "children": [f"Пример. {example}"]})
    return nodes


async def send_commands_card(message: Any, db: Any) -> None:
    from community_bot.blocks import answer_block
    from community_bot.telegraph import publish_commands_guide

    url = await publish_commands_guide(db)
    await answer_block(
        message,
        "commands",
        COMMANDS_CARD_TEXT if url else COMMANDS_CARD_PENDING,
        parse_mode="HTML",
        reply_markup=commands_keyboard(url) if url else None,
    )
